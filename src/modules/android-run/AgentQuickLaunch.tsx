/** Skip-all-prompts flags, so a click drops you straight into a working agent
 * instead of the usual approval dance. */
export const AGENT_QUICK_COMMANDS = {
  claude: "claude --permission-mode bypassPermissions",
  codex: "codex --dangerously-bypass-approvals-and-sandbox",
} as const;

export type QuickAgentId = keyof typeof AGENT_QUICK_COMMANDS;

type Props = {
  /** Project root the agent should start in. */
  projectRoot: string;
  /** Agent already running in the target terminal — launching would type the
   * command straight into its prompt, so the buttons go dead instead. */
  busyAgent?: string | null;
  onLaunch: (
    projectRoot: string,
    command: string,
    agent: QuickAgentId,
  ) => void;
};

const BUTTON =
  "flex size-6 items-center justify-center rounded border border-border text-muted-foreground transition-colors disabled:cursor-not-allowed disabled:opacity-35 disabled:hover:border-border";

/** 一键在当前工程目录开一个已授权的 Claude / Codex 终端。 */
export function AgentQuickLaunch({
  projectRoot,
  busyAgent,
  onLaunch,
}: Props) {
  const busy = !!busyAgent;
  const busyTitle = `当前终端里 ${busyAgent} 正在运行,先退出再启动`;
  return (
    <span className="flex items-center gap-1">
      <button
        type="button"
        aria-label="Claude"
        disabled={busy}
        title={
          busy ? busyTitle : "在当前工程开一个 Claude 终端(已跳过权限确认)"
        }
        onClick={() =>
          onLaunch(projectRoot, AGENT_QUICK_COMMANDS.claude, "claude")
        }
        className={`${BUTTON} hover:border-[#d97757]/60 hover:text-[#d97757]`}
      >
        <ClaudeMark />
      </button>
      <button
        type="button"
        aria-label="Codex"
        disabled={busy}
        title={
          busy ? busyTitle : "在当前工程开一个 Codex 终端(已跳过审批与沙箱)"
        }
        onClick={() =>
          onLaunch(projectRoot, AGENT_QUICK_COMMANDS.codex, "codex")
        }
        className={`${BUTTON} hover:border-foreground/40 hover:text-foreground`}
      >
        <CodexMark />
      </button>
    </span>
  );
}
